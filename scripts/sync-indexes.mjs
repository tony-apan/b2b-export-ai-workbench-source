#!/usr/bin/env node
/**
 * Synchronize the generated direct-entry block in every index.md.
 *
 * The script intentionally indexes only the current directory's direct files
 * and direct child-directory canonical entries. It never recursively flattens
 * a tree into a parent index.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFrontMatter, stringField, stringListField } from './lib/markdown-front-matter.mjs';

const scriptPath = fileURLToPath(import.meta.url);
const root = resolve(dirname(scriptPath), '..');
const checkOnly = process.argv.includes('--check');
const ignoredDirs = new Set(['.git', '.obsidian', 'node_modules', 'dist', '.cache', 'runtime', 'customer-runtime', 'credentials', 'secrets', '.secrets', 'private', 'workspace']);
const beginMarker = '<!-- INDEX:BEGIN generated by scripts/sync-indexes.mjs; do not hand-edit -->';
const endMarker = '<!-- INDEX:END -->';

function walk(dir) {
  const result = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (ignoredDirs.has(entry.name)) continue;
    const target = join(dir, entry.name);
    if (entry.isDirectory()) result.push(...walk(target));
    else result.push(target);
  }
  return result;
}

const metadataCache = new Map();
function parseFrontMatter(filePath) {
  if (metadataCache.has(filePath)) return metadataCache.get(filePath);
  const parsed = readFrontMatter(filePath, { rejectDuplicates: true });
  if (!parsed) throw new Error(`missing front matter or README metadata block: ${relative(root, filePath)}`);
  const stringFields = ['title', 'description', 'type', 'status', 'visibility', 'doc_id', 'when_to_read', 'last_updated'];
  const meta = Object.fromEntries(stringFields.map((field) => {
    if (parsed.data.has(field) && typeof parsed.data.get(field) !== 'string') {
      throw new Error(`${relative(root, filePath)} metadata field ${field} must be a string`);
    }
    return [field, stringField(parsed, field)];
  }));
  if (parsed.data.has('keywords')) {
    const keywords = stringListField(parsed, 'keywords');
    if (!keywords.valid) throw new Error(`${relative(root, filePath)} keywords ${keywords.reason}`);
    meta.keywords = keywords.values;
  } else meta.keywords = [];
  metadataCache.set(filePath, meta);
  return meta;
}

function canonicalEntry(directory) {
  const index = join(directory, 'index.md');
  const readme = join(directory, 'README.md');
  if (existsSync(index)) return index;
  if (existsSync(readme)) return readme;
  return null;
}

function directTargets(indexPath) {
  const directory = dirname(indexPath);
  const targets = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (ignoredDirs.has(entry.name) || entry.name.startsWith('.')) continue;
    const target = join(directory, entry.name);
    if (entry.isDirectory()) {
      const canonical = canonicalEntry(target);
      if (canonical && parseFrontMatter(canonical).type !== 'redirect') targets.push(canonical);
      continue;
    }
    if (target === indexPath || extname(entry.name).toLowerCase() !== '.md') continue;
    if (parseFrontMatter(target).type === 'redirect') continue;
    targets.push(target);
  }
  return targets.sort((a, b) => relative(directory, a).localeCompare(relative(directory, b)));
}

function escapeCell(value) {
  return String(value || '未填写').replaceAll('|', '\\|').replaceAll(/\s+/g, ' ').trim();
}

function whenToRead(type) {
  const map = {
    index: '了解本目录范围或定位下一层入口时',
    meta: '需要理解规则、边界或协作方式时',
    governance: '需要修改规则、发布或验收时',
    source: '需要核对来源、授权或证据时',
    'source-policy': '需要确认来源、版权或发布边界时',
    concept: '需要统一定义或判断框架时',
    playbook: '需要按步骤执行任务时',
    business: '需要确认业务事实、ICP、offer 或 claim 时',
    channel: '需要制定或复盘该渠道动作时',
    metric: '需要定义指标、基线或实验判断时',
    output: '需要查找可复用或已发布产出时',
    template: '新建同类页面或记录时',
    'raw-guide': '处理原始资料或公开边界时',
    evidence: '需要核对验证证据和适用边界时',
    checklist: '执行验收、发布或风险检查时',
    'sub-library': '选择、安装或交付独立子库时',
    adapter: '执行具体工具或部署适配时',
    skill: '判断 AI 是否可以按协议执行时',
  };
  return map[type] || '需要处理本目录对应主题时';
}

function renderBlock(indexPath) {
  const directory = dirname(indexPath);
  const targets = directTargets(indexPath);
  const rows = targets.map((target) => {
    const meta = parseFrontMatter(target);
    const link = relative(directory, target).split(sep).join('/');
    const fileId = meta.doc_id || (target.match(/(?:^|\/)id-(\d{4})-/i)?.[1] ? `ID-${target.match(/(?:^|\/)id-(\d{4})-/i)[1]}` : '—');
    const state = [meta.status || '未填写', meta.visibility || ''].filter(Boolean).join(' / ');
    const readWhen = meta.when_to_read || whenToRead(meta.type);
    const keywords = meta.keywords.length ? meta.keywords.join('、') : '—';
    return `| ${escapeCell(fileId)} | [${escapeCell(meta.title || link)}](${link}) | ${escapeCell(meta.description)} | ${escapeCell(meta.type)} | ${escapeCell(state)} | ${escapeCell(readWhen)} | ${escapeCell(keywords)} |`;
  });
  const empty = '| — | （暂无） | 当前目录暂时没有可公开导航的直接文件或带 canonical 入口的子目录。 | — | — | 先确认是否应创建 index.md、README.md 或把目录标记为实现目录。 | — |';
  return [
    beginMarker,
    '## 当前目录直接入口',
    '',
    '> 本表只列当前目录的直接 Markdown 文件和直接子目录 canonical 入口；description 说明文档解决什么问题，状态列说明当前成熟度/可见性，ID 用于稳定引用；需要继续深入时，请打开对应条目自己的 `index.md` 或 `README.md`。',
    '',
    '| ID | 入口 | 内容说明（description） | 类型 | 状态 / 可见性 | 什么时候读 | 检索词 |',
    '|---|---|---|---|---|---|---|',
    ...(rows.length ? rows : [empty]),
    '',
    endMarker,
  ].join('\n');
}

function freshestDirectDate(indexPath) {
  return directTargets(indexPath)
    .map((target) => parseFrontMatter(target).last_updated)
    .filter((date) => /^\d{4}-\d{2}-\d{2}$/.test(date))
    .sort()
    .at(-1) ?? '';
}
function bumpIndexDate(content, indexPath) {
  const freshest = freshestDirectDate(indexPath);
  const current = parseFrontMatter(indexPath).last_updated;
  if (!freshest || !/^\d{4}-\d{2}-\d{2}$/.test(current) || current >= freshest) return content;
  return content.replace(/^last_updated:\s*["']?[^\n"']+["']?\s*$/m, `last_updated: "${freshest}"`);
}
function syncContent(indexPath) {
  const content = readFileSync(indexPath, 'utf8');
  const block = renderBlock(indexPath);
  const markerRe = /<!-- INDEX:BEGIN generated by scripts\/sync-indexes\.mjs; do not hand-edit -->[\s\S]*?<!-- INDEX:END -->\n?/;
  let next;
  if (markerRe.test(content)) next = content.replace(markerRe, `${block}\n`);
  else {
    const h1 = content.match(/^# .*\n/m);
    if (!h1) next = `${content.trimEnd()}\n\n${block}\n`;
    else {
      const insertAt = h1.index + h1[0].length;
      next = `${content.slice(0, insertAt)}\n${block}\n${content.slice(insertAt)}`;
    }
  }
  return bumpIndexDate(next, indexPath);
}

const indexes = walk(root).filter((file) => file.endsWith(`${sep}index.md`));
const stale = [];
const plannedWrites = [];
try {
  for (const indexPath of indexes) {
    const before = readFileSync(indexPath, 'utf8');
    const after = syncContent(indexPath);
    if (before !== after) {
      stale.push(relative(root, indexPath));
      plannedWrites.push([indexPath, after]);
    }
  }
} catch (error) {
  console.error(`INDEX_SYNC_FAILURE: ${error.message}`);
  process.exit(1);
}
if (!checkOnly) for (const [indexPath, content] of plannedWrites) writeFileSync(indexPath, content);
if (checkOnly && stale.length) {
  console.error(`STALE_INDEXES: ${stale.length}`);
  for (const file of stale) console.error(`- ${file}`);
  console.error('Run: node scripts/sync-indexes.mjs');
  process.exitCode = 1;
} else {
  console.log(`${checkOnly ? 'INDEXES_OK' : 'INDEXES_SYNCED'}: ${indexes.length}`);
  if (!checkOnly && stale.length) for (const file of stale) console.log(`- ${file}`);
}
