function dedupeInlineArrayField(content, field) {
  return content.replace(new RegExp(`^${field}:\\s*\\[([^\\]]*)\\]\\s*$`, 'm'), (line, inner) => {
    const values = [...inner.matchAll(/["']([^"']+)["']/g)].map((match) => match[1]);
    const unique = [...new Set(values)];
    return `${field}: [${unique.map((value) => JSON.stringify(value)).join(', ')}]`;
  });
}
function transform(content, file) {
  let output = content;
  for (const [from, to] of linkReplacements) output = output.split(from).join(to);
  output = output.replace(/\.\.\/ADAPTERS\/[^\"\s\])]+/g, '../30_tasks/index.md');
  if (file === 'tool-field-map.md') output = output.replace('transfer-exercise-record.md', 'failure-diagnosis.md');
  output = dedupeInlineArrayField(dedupeInlineArrayField(output, 'sources'), 'related');
  const marker = `<!-- Generated runtime copy from TEMPLATES/${file}; do not hand-edit this copy in the source package. -->`;
  output = output.replace(/\n<!-- Generated runtime copy from TEMPLATES\/[^>]+ -->\n/g, '\n');
  const end = output.indexOf('\n---', 4);
  if (end === -1) throw new Error(`source template lacks front matter: ${file}`);
  const insertAt = end + 4;
  return `${output.slice(0, insertAt)}\n${marker}${output.slice(insertAt)}`;
}

function metadata(content, field) {
  return content.match(new RegExp(`^${field}:\\s*[\"']?([^\\n\"']+)[\"']?\\s*$`, 'm'))?.[1]?.trim() ?? '';
}
function runtimeIndexTable(sourceContents) {
  const rows = runtimeTemplateFiles.map((file) => {
    const content = sourceContents.get(file);
    const title = metadata(content, 'title') || file;
    const description = metadata(content, 'description') || '未填写 description';
    const type = metadata(content, 'type') || 'template';
    return `| [${title}](${file}) | ${description.replaceAll('|', '\\|')} | ${type} | 需要填写同类记录时 |`;
  });
  return `<!-- INDEX:BEGIN generated by scripts/sync-indexes.mjs; do not hand-edit -->
## 当前目录直接入口

> 本表只列当前目录的直接模板文件；需要继续执行时，请回到对应的工作区层级入口。

| 入口 | 内容说明（description） | 类型 | 什么时候读 |
|---|---|---|---|
${rows.join('\n')}

<!-- INDEX:END -->`;
}

function expectedFiles() {
  const sourceContents = new Map();
  for (const file of runtimeTemplateFiles) {
    const sourcePath = join(sourceDir, file);
    if (!existsSync(sourcePath)) throw new Error(`missing canonical template: ${relative(libraryRoot, sourcePath)}`);
    sourceContents.set(file, readFileSync(sourcePath, 'utf8'));
  }
  const readme = runtimeReadme.replace(/<!-- INDEX:BEGIN generated by scripts\/sync-indexes\.mjs; do not hand-edit -->[\s\S]*?<!-- INDEX:END -->/, runtimeIndexTable(sourceContents));
  const files = new Map([['README.md', readme]]);
  for (const file of runtimeTemplateFiles) files.set(file, transform(sourceContents.get(file), file));
  return files;
}

function actualFiles() {
  if (!existsSync(runtimeDir)) return new Map();
  const files = new Map();
  for (const entry of readdirSync(runtimeDir, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith('.md')) files.set(entry.name, readFileSync(join(runtimeDir, entry.name), 'utf8'));
  }
  return files;
}

const expected = expectedFiles();
const actual = actualFiles();
const problems = [];
for (const [file, content] of expected) {
  const actualContent = actual.get(file);
  if (actualContent === undefined || actualContent !== content) problems.push(`stale or missing runtime template: WORKSPACE-TEMPLATE/TEMPLATES/${file}`);
}
for (const file of actual.keys()) {
  if (!expected.has(file) && file !== 'index.md') problems.push(`unexpected runtime template: WORKSPACE-TEMPLATE/TEMPLATES/${file}`);
}

if (checkOnly) {
  if (problems.length) {
    for (const problem of problems) console.error(`FAIL: ${problem}`);
    process.exitCode = 1;
  } else {
    console.log(`WORKSPACE_TEMPLATE_SYNC_PASS: ${expected.size} generated files are current`);
  }
} else {
  mkdirSync(runtimeDir, { recursive: true });
  for (const [file, content] of expected) {
    const target = join(runtimeDir, file);
    writeFileSync(target, content);
  }
  console.log(`WORKSPACE_TEMPLATE_SYNCED: ${expected.size} files`);
}
